//! The model's Nickel contracts, written from its types' JSON Schema (FD-046-D15).
//!
//! schemars derives each genie-model type's JSON Schema; [`contracts`] writes it as one Nickel
//! record of contracts, one per definition in name order, which a mod's values and an editor's
//! language server check against. [`schema_hash`] keys the model cache by them (D18).

use genie_error::GenieError;
use schemars::Schema;
use serde_json::Map;
use serde_json::Value;
use sha2::Digest;
use sha2::Sha256;
use std::collections::BTreeMap;
use std::fmt::Write;
use std::fs;
use std::io::Error as IoError;
use std::path::Path;

/// The words Nickel reserves, which a field name must quote.
const KEYWORDS: [&str; 22] = [
    "if",
    "then",
    "else",
    "let",
    "in",
    "fun",
    "import",
    "match",
    "null",
    "true",
    "false",
    "forall",
    "rec",
    "default",
    "doc",
    "optional",
    "priority",
    "force",
    "not_exported",
    "Dyn",
    "Number",
    "include",
];

/// The schema's definitions as one Nickel record of contracts, in name order.
///
/// The root's definition is among them. An object becomes a record contract of its fields, an
/// enum of names an enum contract, a bounded integer a predicate, a number `Number`, a string
/// `String`, a bool `Bool`, an array `Array` of its item and an optional field `| optional`.
///
/// # Errors
///
/// A [`GenieError`] for a schema shape the contracts have no form for.
pub fn contracts(schema: &Schema) -> Result<String, GenieError> {
    let root = schema
        .as_object()
        .ok_or_else(|| GenieError::invalid_input("a JSON Schema that is no object"))?;
    let mut definitions: BTreeMap<&str, &Value> = BTreeMap::new();
    if let Some(Value::Object(defs)) = root.get("$defs") {
        definitions.extend(defs.iter().map(|(name, value)| (name.as_str(), value)));
    }
    let root_value = schema.as_value();
    if let Some(Value::String(title)) = root.get("title") {
        let _ = definitions.insert(title.as_str(), root_value);
    }
    let mut out = String::from(
        "# Generated by just contracts from genie-model's types (FD-046-D15). Do not edit.\n{\n",
    );
    for (name, definition) in definitions {
        let contract = contract(definition, 1).map_err(|e| e.with("definition", name))?;
        let doc = description(definition);
        let _ = writeln!(out, "  {}{doc} = {contract},", field_name(name));
    }
    out.push_str("}\n");
    Ok(out)
}

/// The SHA-256 of the contracts' text: the model's schema hash, a part of the cache's key (D18).
#[must_use]
pub fn schema_hash(contracts: &str) -> [u8; 32] {
    Sha256::digest(contracts.as_bytes()).into()
}

/// What [`write_or_check`] found or did.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Outcome {
    /// The file holds the contracts now.
    Written,
    /// The check found the file current.
    Current,
    /// The check found the file differs from the contracts.
    Stale,
}

/// The contracts `text` at `path`: written (its folder made), or with `check` compared with the
/// file.
///
/// # Errors
///
/// A [`GenieError`] when the file or its folder cannot be written.
pub fn write_or_check(path: &Path, text: &str, check: bool) -> Result<Outcome, GenieError> {
    if check {
        let current = fs::read_to_string(path).ok().as_deref() == Some(text);
        return Ok(if current {
            Outcome::Current
        } else {
            Outcome::Stale
        });
    }
    let failed = |e: IoError| {
        GenieError::invalid_input("contracts that cannot be written")
            .with("path", path.display())
            .with("why", e)
    };
    if let Some(folder) = path.parent() {
        fs::create_dir_all(folder).map_err(failed)?;
    }
    fs::write(path, text).map_err(failed)?;
    Ok(Outcome::Written)
}

/// The contract of one schema, at `depth` levels of indentation.
fn contract(schema: &Value, depth: usize) -> Result<String, GenieError> {
    let Value::Object(object) = schema else {
        return match schema {
            Value::Bool(true) => Ok("Dyn".to_owned()),
            _ => Err(unknown(schema)),
        };
    };
    if let Some(Value::String(reference)) = object.get("$ref") {
        let name = reference.rsplit('/').next().unwrap_or(reference);
        return Ok(field_name(name));
    }
    if let Some(Value::Array(variants)) = object.get("oneOf").or_else(|| object.get("anyOf")) {
        return alternatives(variants, depth);
    }
    if let Some(Value::Array(names)) = object.get("enum") {
        return tags(names.iter().map(|n| (n, None)));
    }
    if let Some(name) = object.get("const") {
        return tags([(name, None)].into_iter());
    }
    match kind(object)? {
        "integer" => Ok(integer(object)),
        "number" => Ok("Number".to_owned()),
        "string" => Ok("String".to_owned()),
        "boolean" => Ok("Bool".to_owned()),
        "null" => Ok("Dyn".to_owned()),
        "array" => array(object, depth),
        "object" => record(object, depth),
        _ => Err(unknown(schema)),
    }
}

/// The schema's type, the non-null one of a nullable type.
fn kind(object: &Map<String, Value>) -> Result<&str, GenieError> {
    match object.get("type") {
        Some(Value::String(kind)) => Ok(kind),
        Some(Value::Array(kinds)) => {
            let mut named = kinds
                .iter()
                .filter_map(Value::as_str)
                .filter(|k| *k != "null");
            match (named.next(), named.next()) {
                (Some(kind), None) => Ok(kind),
                _ => Err(unknown(&Value::Object(object.clone()))),
            }
        }
        _ => Err(unknown(&Value::Object(object.clone()))),
    }
}

/// A predicate on an integer within the schema's bounds.
fn integer(object: &Map<String, Value>) -> String {
    let mut tests = vec!["std.is_number x".to_owned(), "x % 1 == 0".to_owned()];
    if let Some(min) = object.get("minimum") {
        tests.push(format!("{min} <= x"));
    }
    if let Some(max) = object.get("maximum") {
        tests.push(format!("x <= {max}"));
    }
    format!(
        "std.contract.from_predicate (fun x => {})",
        tests.join(" && ")
    )
}

/// An array of its items' contract; a tuple's items are one array of any value.
fn array(object: &Map<String, Value>, depth: usize) -> Result<String, GenieError> {
    match object.get("items") {
        Some(items) => Ok(format!("Array ({})", contract(items, depth)?)),
        None => Ok("Array Dyn".to_owned()),
    }
}

/// A record contract of the schema's properties, or a dictionary of its additional ones.
fn record(object: &Map<String, Value>, depth: usize) -> Result<String, GenieError> {
    let Some(Value::Object(properties)) = object.get("properties") else {
        return match object.get("additionalProperties") {
            Some(Value::Bool(false)) | None => Ok("{}".to_owned()),
            Some(values) => Ok(format!("{{ _ | {} }}", contract(values, depth)?)),
        };
    };
    let required: Vec<&str> = match object.get("required") {
        Some(Value::Array(names)) => names.iter().filter_map(Value::as_str).collect(),
        _ => Vec::new(),
    };
    let indent = "  ".repeat(depth + 1);
    let mut out = String::from("{\n");
    for (name, schema) in properties {
        let field = contract(schema, depth + 1).map_err(|e| e.with("field", name))?;
        let optional = if required.contains(&name.as_str()) {
            ""
        } else {
            " | optional"
        };
        let doc = description(schema);
        let _ = writeln!(
            out,
            "{indent}{} | {field}{optional}{doc},",
            field_name(name)
        );
    }
    let _ = write!(out, "{}}}", "  ".repeat(depth));
    Ok(out)
}

/// The alternatives of a `oneOf` or `anyOf`: a nullable one is its non-null alternative, and an
/// enum's variants (names, and single-property objects for variants that hold a value) are one
/// enum contract.
fn alternatives(variants: &[Value], depth: usize) -> Result<String, GenieError> {
    let present: Vec<&Value> = variants
        .iter()
        .filter(|v| v.get("type").and_then(Value::as_str) != Some("null"))
        .collect();
    if let [single] = present.as_slice() {
        return contract(single, depth);
    }
    let mut tags_of = Vec::new();
    for variant in &present {
        match variant {
            Value::Object(v) if v.contains_key("enum") || v.contains_key("const") => {
                let names = v.get("enum").and_then(Value::as_array).cloned();
                let names = names.unwrap_or_else(|| v.get("const").cloned().into_iter().collect());
                tags_of.extend(names.into_iter().map(|n| (n, None)));
            }
            Value::Object(v) => {
                let Some(Value::Object(properties)) = v.get("properties") else {
                    return Err(unknown(variant));
                };
                let [(name, payload)] = properties.iter().collect::<Vec<_>>()[..] else {
                    return Err(unknown(variant));
                };
                tags_of.push((Value::String(name.clone()), Some(contract(payload, depth)?)));
            }
            _ => return Err(unknown(variant)),
        }
    }
    tags(tags_of.iter().map(|(n, p)| (n, p.clone())))
}

/// An enum contract of tags, each with the contract of the value it holds, if any.
fn tags<'a>(
    names: impl Iterator<Item = (&'a Value, Option<String>)>,
) -> Result<String, GenieError> {
    let mut rows = Vec::new();
    for (name, payload) in names {
        let Value::String(name) = name else {
            return Err(unknown(name));
        };
        rows.push(payload.map_or_else(
            || format!("'{}", tag(name)),
            |payload| format!("'{} ({payload})", tag(name)),
        ));
    }
    Ok(format!("[| {} |]", rows.join(", ")))
}

/// A tag's name, quoted where it is no identifier.
fn tag(name: &str) -> String {
    if is_identifier(name) {
        name.to_owned()
    } else {
        quoted(name)
    }
}

/// A field's name, quoted where it is no identifier or a Nickel word.
fn field_name(name: &str) -> String {
    if is_identifier(name) && !KEYWORDS.contains(&name) {
        name.to_owned()
    } else {
        quoted(name)
    }
}

/// Whether `name` is a Nickel identifier.
fn is_identifier(name: &str) -> bool {
    let mut chars = name.chars();
    chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '-' | '\''))
}

/// The schema's description as a `| doc` annotation, if it has one.
fn description(schema: &Value) -> String {
    schema
        .get("description")
        .and_then(Value::as_str)
        .map_or_else(String::new, |d| format!(" | doc {}", quoted(d)))
}

/// `text` as a Nickel string literal.
fn quoted(text: &str) -> String {
    let mut out = String::from("\"");
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '%' => out.push_str("\\%"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// The error of a schema shape the contracts have no form for.
fn unknown(schema: &Value) -> GenieError {
    GenieError::invalid_input("a JSON Schema shape the contracts have no form for")
        .with("schema", schema)
}

